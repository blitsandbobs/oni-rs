//! Generates `docs/lua-api.md` from the sources on every build: the
//! scenario host's Lua functions (`src/script/*.rs`, in the order
//! `script/mod.rs` registers them: each `r.def("name", …)`, its arguments
//! from the closure, its description from the comment above)
//! and the level scripts' engine commands (`src/mission/commands/*.rs`, in
//! the order a command falls through them: each match arm, its description
//! from the comment at its top). The file is
//! written only when it changes.

use std::path::Path;

fn main() {
    println!("cargo:rerun-if-changed=src/script");
    println!("cargo:rerun-if-changed=src/mission/commands");
    let dir = Path::new(env!("CARGO_MANIFEST_DIR"));
    let mut doc = String::from(
        "# Lua API reference\n\n\
         Generated by `crates/oni/build.rs` from `src/script/` and\n\
         `src/mission/commands/` on every build — don't edit; change the\n\
         comments there. How the two Lua surfaces work: `docs/lua.md`.\n\n\
         ## Scenario functions\n\n\
         Globals a scenario (`--script file.lua`) can call. Types: `int`,\n\
         `number`, `string`, `bool`, `table`, `function`, `any`; `?` optional.\n",
    );
    for (title, src) in areas(&dir.join("src/script")) {
        doc.push_str(&format!(
            "\n### {title}\n\n| Function | Description |\n|---|---|\n"
        ));
        for (name, args, text) in scenario_functions(&src) {
            doc.push_str(&format!("| `{name}({args})` | {} |\n", cell(&text)));
        }
    }
    doc.push_str(
        "\n## Engine commands for level scripts\n\n\
         What the translated BSL calls as `C.name(…)` (`docs/lua.md`). Names\n\
         starting with `@` are the prelude's own hooks. Commands not listed\n\
         are logged once and do nothing.\n",
    );
    for (title, src) in command_areas(&dir.join("src/mission/commands")) {
        doc.push_str(&format!(
            "\n### {title}\n\n| Command | Description |\n|---|---|\n"
        ));
        for (names, text) in engine_commands(&src) {
            let names: Vec<String> = names.iter().map(|n| format!("`{n}`")).collect();
            doc.push_str(&format!("| {} | {} |\n", names.join(", "), cell(&text)));
        }
    }
    let out = dir.join("../../docs/lua-api.md");
    if std::fs::read_to_string(&out).ok().as_deref() != Some(doc.as_str()) {
        let _ = std::fs::write(&out, doc);
    }
}

/// The modules of `dir` in the order its `mod.rs` registers them
/// (`name::register(…)`): each one's title (its first `//!` line, past a
/// `…: `) and source.
fn areas(dir: &Path) -> Vec<(String, String)> {
    let main = std::fs::read_to_string(dir.join("mod.rs")).unwrap_or_default();
    main.lines()
        .filter_map(|l| {
            l.trim()
                .split_once("::register(")
                .map(|(m, _)| m.to_string())
        })
        .filter_map(|m| area(dir, &m))
        .collect()
}

/// The engine-command modules of `dir` in the order a command falls
/// through them: the one `mod.rs`'s `dispatch` calls, then each one's next
/// (`super::name::dispatch(`). Fails the build unless the chain reaches
/// every module `mod.rs` declares, once each.
fn command_areas(dir: &Path) -> Vec<(String, String)> {
    let next = |src: &str| {
        src.lines()
            .filter_map(|l| l.split_once("::dispatch(state").map(|(m, _)| m.trim()))
            .map(|m| {
                m.trim_start_matches("_ =>")
                    .trim()
                    .trim_start_matches("super::")
                    .to_string()
            })
            .next()
    };
    let main = std::fs::read_to_string(dir.join("mod.rs")).unwrap_or_default();
    let declared: Vec<&str> = main
        .lines()
        .filter_map(|l| l.strip_prefix("mod ")?.strip_suffix(';'))
        .collect();
    let (mut out, mut seen) = (Vec::new(), Vec::new());
    let mut m = next(&main);
    while let Some(name) = m.filter(|n| !seen.contains(n)) {
        let (title, src) =
            area(dir, &name).unwrap_or_else(|| panic!("commands chain: no module {name:?}"));
        m = next(&src);
        seen.push(name);
        out.push((title, src));
    }
    let mut missed: Vec<&&str> = declared
        .iter()
        .filter(|d| !seen.iter().any(|s| s == *d))
        .collect();
    missed.sort();
    assert!(missed.is_empty(), "commands chain misses {missed:?} (each area's `_ =>` must call the next: super::name::dispatch(state, …))");
    out
}

/// Module `name` of `dir`: its title (its first `//!` line, past a `…: `)
/// and source.
fn area(dir: &Path, name: &str) -> Option<(String, String)> {
    let src = std::fs::read_to_string(dir.join(format!("{name}.rs"))).ok()?;
    let first = src.lines().next()?.trim_start_matches("//!").trim();
    let title = first.split_once(": ").map_or(first, |(_, t)| t);
    let mut title = title.trim_end_matches('.').to_string();
    if let Some(c) = title.get(..1) {
        title.replace_range(..1, &c.to_uppercase());
    }
    Some((title, src))
}

/// A description fit for a table cell.
fn cell(text: &str) -> String {
    text.replace('|', "\\|")
}

/// The comment lines (`// …`) right above line `at`, skipping `let h = …`
/// lines and blank lines, joined.
fn comment_above(lines: &[&str], mut at: usize) -> String {
    while at > 0 && {
        let l = lines[at - 1].trim();
        l.starts_with("let h") || l.is_empty() && at >= 2 && lines[at - 2].trim().starts_with("//")
    } {
        at -= 1;
        if lines[at].trim().is_empty() {
            break;
        }
    }
    let mut out = Vec::new();
    while at > 0 && lines[at - 1].trim_start().starts_with("//") {
        at -= 1;
        let text = lines[at].trim_start().trim_start_matches('/').trim();
        // (Section banners, `--- … ---`, aren't descriptions.)
        if !text.starts_with("---") {
            out.push(text);
        }
    }
    out.reverse();
    out.join(" ")
}

/// A comment without the call it opens with (`name(…) → …`, `name(…): …`),
/// which the table shows already.
fn unsigned(name: &str, text: &str) -> String {
    let Some(rest) = text.strip_prefix(name).filter(|r| r.starts_with('(')) else {
        return text.to_string();
    };
    let mut depth = 0;
    for (k, ch) in rest.char_indices() {
        match ch {
            '(' => depth += 1,
            ')' => depth -= 1,
            _ => {}
        }
        if depth == 0 {
            let after = rest[k + 1..].trim_start();
            for sep in ["→", ":", "—", "-"] {
                if let Some(r) = after.strip_prefix(sep) {
                    return r.trim_start().to_string();
                }
            }
            return text.to_string();
        }
    }
    text.to_string()
}

/// A Rust type as the Lua side sees it.
fn lua_type(t: &str) -> String {
    let t = t.trim();
    if let Some(inner) = t.strip_prefix("Option<").and_then(|r| r.strip_suffix('>')) {
        return format!("{}?", lua_type(inner));
    }
    match t {
        "bool" => "bool",
        "String" | "mlua::String" => "string",
        "f32" | "f64" => "number",
        "u8" | "u16" | "u32" | "u64" | "usize" | "i16" | "i32" | "i64" => "int",
        "mlua::Function" | "Function" => "function",
        "mlua::Value" | "Value" | "mlua::MultiValue" => "any",
        _ if t.starts_with("Vec<") || t.contains("Table") || t.starts_with('[') => "table",
        _ => "any",
    }
    .to_string()
}

/// Splits `a, b<c, d>, e` at its top-level commas.
fn split_top(s: &str) -> Vec<String> {
    let (mut out, mut cur, mut depth) = (Vec::new(), String::new(), 0i32);
    for ch in s.chars() {
        match ch {
            '<' | '(' | '[' => depth += 1,
            '>' | ')' | ']' => depth -= 1,
            ',' if depth == 0 => {
                out.push(std::mem::take(&mut cur).trim().to_string());
                continue;
            }
            _ => {}
        }
        cur.push(ch);
    }
    if !cur.trim().is_empty() {
        out.push(cur.trim().to_string());
    }
    out
}

/// A closure's arguments (`(a, b): (T, U)`, `a: T`, ``) as `a: t, b: u`.
fn arguments(sig: &str) -> String {
    let sig = sig.trim();
    if sig == "()" || sig.is_empty() {
        return String::new();
    }
    let Some((pat, ty)) = sig.split_once(':') else {
        return String::new();
    };
    let (pat, ty) = (pat.trim(), ty.trim());
    if pat == "()" {
        return String::new();
    }
    let strip = |s: &str| {
        s.strip_prefix('(')
            .and_then(|r| r.strip_suffix(')'))
            .map(str::to_string)
            .unwrap_or_else(|| s.to_string())
    };
    if pat.starts_with('(') {
        let names = split_top(&strip(pat));
        let types = split_top(&strip(ty));
        names
            .iter()
            .zip(types.iter().chain(std::iter::repeat(&String::new())))
            .map(|(n, t)| {
                format!(
                    "{}: {}",
                    n.trim_start_matches("mut ").trim_start_matches('_'),
                    lua_type(t)
                )
            })
            .collect::<Vec<_>>()
            .join(", ")
    } else {
        format!("{}: {}", pat.trim_start_matches('_'), lua_type(ty))
    }
}

/// Each `r.def("name", |_, host, ARGS| …)`: its name, arguments and
/// comment.
fn scenario_functions(src: &str) -> Vec<(String, String, String)> {
    let lines: Vec<&str> = src.lines().collect();
    let mut out = Vec::new();
    for (i, l) in lines.iter().enumerate() {
        if !l.trim_start().starts_with("r.def(") {
            continue;
        }
        // The call, whitespace folded, over as many lines as it takes.
        let rest: String = lines[i..(i + 20).min(lines.len())]
            .join(" ")
            .split_whitespace()
            .collect::<Vec<_>>()
            .join(" ");
        let Some(name) = rest.split('"').nth(1) else {
            continue;
        };
        // The closure's arguments: past `|lua, host, ` up to the next `|`.
        let args = rest
            .split_once('|')
            .and_then(|(_, r)| r.split_once(", "))
            .and_then(|(_, r)| r.split_once(", "))
            .and_then(|(_, r)| r.split_once('|'))
            .map(|(a, _)| arguments(a))
            .unwrap_or_default();
        out.push((
            name.to_string(),
            args,
            unsigned(name, &comment_above(&lines, i)),
        ));
    }
    out
}

/// Each `"name" [| "name2" …] =>` arm of the command dispatch, with the
/// comment at the top of its body.
fn engine_commands(src: &str) -> Vec<(Vec<String>, String)> {
    let lines: Vec<&str> = src.lines().collect();
    let mut out = Vec::new();
    for (i, l) in lines.iter().enumerate() {
        let t = l.trim_start();
        if l.len() - t.len() != 8 || !t.starts_with('"') {
            continue;
        }
        // (An arm's names can run on over lines starting with `|`.)
        let mut head = t.to_string();
        let mut end = i;
        while !head.contains("=>")
            && lines
                .get(end + 1)
                .is_some_and(|n| n.trim_start().starts_with('|'))
        {
            end += 1;
            head.push(' ');
            head.push_str(lines[end].trim());
        }
        if !head.contains("=>") {
            continue;
        }
        let head = head.split("=>").next().unwrap_or("");
        let names: Vec<String> = head
            .split('|')
            .filter_map(|n| {
                n.trim()
                    .strip_prefix('"')?
                    .strip_suffix('"')
                    .map(String::from)
            })
            .collect();
        if names.is_empty() {
            continue;
        }
        // Its comment: above the arm, else at the top of its body.
        let mut text = comment_above(&lines, i);
        if text.is_empty() {
            text = lines[end + 1..]
                .iter()
                .map(|b| b.trim_start())
                .take_while(|b| b.starts_with("//"))
                .map(|b| b.trim_start_matches('/').trim())
                .collect::<Vec<_>>()
                .join(" ");
        }
        out.push((names, text));
    }
    out
}
