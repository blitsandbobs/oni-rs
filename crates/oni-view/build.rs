//! Generates `docs/lua-api.md` from the sources on every build: the
//! scenario host's Lua functions (`src/script.rs`: each `g.set("name", …)`,
//! its arguments from the closure, its description from the comment above)
//! and the level scripts' engine commands (`src/mission/commands.rs`: each
//! match arm, its description from the comment at its top). The file is
//! written only when it changes.

use std::path::Path;

fn main() {
    println!("cargo:rerun-if-changed=src/script.rs");
    println!("cargo:rerun-if-changed=src/mission/commands.rs");
    let dir = Path::new(env!("CARGO_MANIFEST_DIR"));
    let script = std::fs::read_to_string(dir.join("src/script.rs")).unwrap_or_default();
    let commands = std::fs::read_to_string(dir.join("src/mission/commands.rs")).unwrap_or_default();
    let mut doc = String::from(
        "# Lua API reference\n\n\
         Generated by `crates/oni-view/build.rs` from `src/script.rs` and\n\
         `src/mission/commands.rs` on every build — don't edit; change the\n\
         comments there. How the two Lua surfaces work: `docs/lua.md`.\n\n\
         ## Scenario functions\n\n\
         Globals a scenario (`--script file.lua`) can call. Types: `int`,\n\
         `number`, `string`, `bool`, `table`, `function`, `any`; `?` optional.\n\n\
         | Function | Description |\n|---|---|\n",
    );
    for (name, args, text) in scenario_functions(&script) {
        doc.push_str(&format!("| `{name}({args})` | {} |\n", cell(&text)));
    }
    doc.push_str(
        "\n## Engine commands for level scripts\n\n\
         What the translated BSL calls as `C.name(…)` (`docs/lua.md`). Names\n\
         starting with `@` are the prelude's own hooks. Commands not listed\n\
         are logged once and do nothing.\n\n\
         | Command | Description |\n|---|---|\n",
    );
    for (names, text) in engine_commands(&commands) {
        let names: Vec<String> = names.iter().map(|n| format!("`{n}`")).collect();
        doc.push_str(&format!("| {} | {} |\n", names.join(", "), cell(&text)));
    }
    let out = dir.join("../../docs/lua-api.md");
    if std::fs::read_to_string(&out).ok().as_deref() != Some(doc.as_str()) {
        let _ = std::fs::write(&out, doc);
    }
}

/// A description fit for a table cell.
fn cell(text: &str) -> String {
    text.replace('|', "\\|")
}

/// The comment lines (`// …`) right above line `at`, skipping `let h = …`
/// lines and blank lines, joined.
fn comment_above(lines: &[&str], mut at: usize) -> String {
    while at > 0 && {
        let l = lines[at - 1].trim();
        l.starts_with("let h") || l.is_empty() && at >= 2 && lines[at - 2].trim().starts_with("//")
    } {
        at -= 1;
        if lines[at].trim().is_empty() {
            break;
        }
    }
    let mut out = Vec::new();
    while at > 0 && lines[at - 1].trim_start().starts_with("//") {
        at -= 1;
        let text = lines[at].trim_start().trim_start_matches('/').trim();
        // (Section banners, `--- … ---`, aren't descriptions.)
        if !text.starts_with("---") {
            out.push(text);
        }
    }
    out.reverse();
    out.join(" ")
}

/// A comment without the call it opens with (`name(…) → …`, `name(…): …`),
/// which the table shows already.
fn unsigned(name: &str, text: &str) -> String {
    let Some(rest) = text.strip_prefix(name).filter(|r| r.starts_with('(')) else {
        return text.to_string();
    };
    let mut depth = 0;
    for (k, ch) in rest.char_indices() {
        match ch {
            '(' => depth += 1,
            ')' => depth -= 1,
            _ => {}
        }
        if depth == 0 {
            let after = rest[k + 1..].trim_start();
            for sep in ["→", ":", "—", "-"] {
                if let Some(r) = after.strip_prefix(sep) {
                    return r.trim_start().to_string();
                }
            }
            return text.to_string();
        }
    }
    text.to_string()
}

/// A Rust type as the Lua side sees it.
fn lua_type(t: &str) -> String {
    let t = t.trim();
    if let Some(inner) = t.strip_prefix("Option<").and_then(|r| r.strip_suffix('>')) {
        return format!("{}?", lua_type(inner));
    }
    match t {
        "bool" => "bool",
        "String" | "mlua::String" => "string",
        "f32" | "f64" => "number",
        "u8" | "u16" | "u32" | "u64" | "usize" | "i16" | "i32" | "i64" => "int",
        "mlua::Function" | "Function" => "function",
        "mlua::Value" | "Value" | "mlua::MultiValue" => "any",
        _ if t.starts_with("Vec<") || t.contains("Table") || t.starts_with('[') => "table",
        _ => "any",
    }
    .to_string()
}

/// Splits `a, b<c, d>, e` at its top-level commas.
fn split_top(s: &str) -> Vec<String> {
    let (mut out, mut cur, mut depth) = (Vec::new(), String::new(), 0i32);
    for ch in s.chars() {
        match ch {
            '<' | '(' | '[' => depth += 1,
            '>' | ')' | ']' => depth -= 1,
            ',' if depth == 0 => {
                out.push(std::mem::take(&mut cur).trim().to_string());
                continue;
            }
            _ => {}
        }
        cur.push(ch);
    }
    if !cur.trim().is_empty() {
        out.push(cur.trim().to_string());
    }
    out
}

/// A closure's arguments (`(a, b): (T, U)`, `a: T`, ``) as `a: t, b: u`.
fn arguments(sig: &str) -> String {
    let sig = sig.trim();
    if sig == "()" || sig.is_empty() {
        return String::new();
    }
    let Some((pat, ty)) = sig.split_once(':') else {
        return String::new();
    };
    let (pat, ty) = (pat.trim(), ty.trim());
    if pat == "()" {
        return String::new();
    }
    let strip = |s: &str| {
        s.strip_prefix('(')
            .and_then(|r| r.strip_suffix(')'))
            .map(str::to_string)
            .unwrap_or_else(|| s.to_string())
    };
    if pat.starts_with('(') {
        let names = split_top(&strip(pat));
        let types = split_top(&strip(ty));
        names
            .iter()
            .zip(types.iter().chain(std::iter::repeat(&String::new())))
            .map(|(n, t)| {
                format!(
                    "{}: {}",
                    n.trim_start_matches("mut ").trim_start_matches('_'),
                    lua_type(t)
                )
            })
            .collect::<Vec<_>>()
            .join(", ")
    } else {
        format!("{}: {}", pat.trim_start_matches('_'), lua_type(ty))
    }
}

/// Each `g.set("name", lua.create_function(move |_, ARGS| …))`: its name,
/// arguments and comment.
fn scenario_functions(src: &str) -> Vec<(String, String, String)> {
    let lines: Vec<&str> = src.lines().collect();
    let mut out = Vec::new();
    for (i, l) in lines.iter().enumerate() {
        if l.trim() != "g.set(" {
            continue;
        }
        let Some(name) = lines
            .get(i + 1)
            .and_then(|n| n.trim().strip_prefix('"'))
            .and_then(|n| n.split('"').next())
        else {
            continue;
        };
        // The closure's arguments: between the first `|_, ` (or `|lua, `)
        // and the next `|`, over as many lines as it takes.
        let rest: String = lines[i + 2..(i + 20).min(lines.len())]
            .join(" ")
            .split_whitespace()
            .collect::<Vec<_>>()
            .join(" ");
        let args = rest
            .split_once("create_function(")
            .and_then(|(_, r)| r.split_once('|'))
            .and_then(|(_, r)| r.split_once(", "))
            .and_then(|(_, r)| r.split_once('|'))
            .map(|(a, _)| arguments(a))
            .unwrap_or_default();
        out.push((
            name.to_string(),
            args,
            unsigned(name, &comment_above(&lines, i)),
        ));
    }
    out
}

/// Each `"name" [| "name2" …] =>` arm of the command dispatch, with the
/// comment at the top of its body.
fn engine_commands(src: &str) -> Vec<(Vec<String>, String)> {
    let lines: Vec<&str> = src.lines().collect();
    let mut out = Vec::new();
    for (i, l) in lines.iter().enumerate() {
        let t = l.trim_start();
        if l.len() - t.len() != 8 || !t.starts_with('"') {
            continue;
        }
        // (An arm's names can run on over lines starting with `|`.)
        let mut head = t.to_string();
        let mut end = i;
        while !head.contains("=>")
            && lines
                .get(end + 1)
                .is_some_and(|n| n.trim_start().starts_with('|'))
        {
            end += 1;
            head.push(' ');
            head.push_str(lines[end].trim());
        }
        if !head.contains("=>") {
            continue;
        }
        let head = head.split("=>").next().unwrap_or("");
        let names: Vec<String> = head
            .split('|')
            .filter_map(|n| {
                n.trim()
                    .strip_prefix('"')?
                    .strip_suffix('"')
                    .map(String::from)
            })
            .collect();
        if names.is_empty() {
            continue;
        }
        // Its comment: above the arm, else at the top of its body.
        let mut text = comment_above(&lines, i);
        if text.is_empty() {
            text = lines[end + 1..]
                .iter()
                .map(|b| b.trim_start())
                .take_while(|b| b.starts_with("//"))
                .map(|b| b.trim_start_matches('/').trim())
                .collect::<Vec<_>>()
                .join(" ");
        }
        out.push((names, text));
    }
    out
}
